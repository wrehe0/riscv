.section .text.init
.global _start

_start:
    # 1. Отключаем все ядра, кроме основного (hart 0)
    csrr a0, mhartid            # Прочитать ID текущего ядра
    bnez a0, park               # Если это не ядро 0, отправляем в бесконечный цикл

    # 2. Настраиваем указатель стека (SP)
    la sp, _stack_top

    # 3. Переходим к коду на C с сохранением адреса возврата
    jal ra, main                # Переходим в main. Когда main завершится, он вернется на строку ниже

    # 4. Ловушка на случай, если main всё-таки завершился
    # (Например, если вы забыли вызвать poweroff() в конце)
    tail_loop:
        wfi                     # Переводим процессор в энергосберегающий режим сна
        j tail_loop             # Если прерывание разбудит процессор, снова засыпаем

park:
    wfi                         # Ожидание прерывания (сон для остальных ядер)
    j park
